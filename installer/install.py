"""
roleplay-slim installer for Mutsumi Desktop Pet (若叶睦桌宠).

Run once, then forget. Patches the game's API endpoint to route through a
local compression proxy. No configuration needed by the end user.

Usage:
    python install.py          # auto-detect pet directory from script location
    python install.py E:\壁纸\若叶睦桌宠\小睦1.9.0   # explicit path
"""

